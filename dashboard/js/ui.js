export function toast(msg) {
  document.querySelectorAll('.toast').forEach(t => t.remove());
  const t = document.createElement('div');
  t.className = 'toast'; t.setAttribute('role', 'status'); t.textContent = msg;
  document.body.appendChild(t);
  setTimeout(() => t.remove(), 2600);
}

export async function copyText(text, label = 'Copied') {
  try { await navigator.clipboard.writeText(text); toast(label); }
  catch { toast('Copy failed'); }
}

/** Replace a region's HTML only when it changed, so live updates don't reset scroll, focus or animations. */
export function patch(el, html) {
  if (!el) return false;
  if (el.__html === html) return false;
  el.__html = html; el.innerHTML = html;
  return true;
}

/** Modal sheet. Returns a close() function. */
export function sheet(html, { onClose, cls = 'sheet' } = {}) {
  const scrim = document.createElement('div');
  scrim.className = 'scrim';
  scrim.innerHTML = `<div class="${cls}" role="dialog" aria-modal="true">${html}</div>`;
  const prev = document.activeElement;
  const close = () => { scrim.remove(); document.removeEventListener('keydown', onKey); onClose?.(); prev?.focus?.(); };
  const onKey = e => { if (e.key === 'Escape') close(); };
  scrim.addEventListener('click', e => { if (e.target === scrim) close(); });
  document.addEventListener('keydown', onKey);
  document.body.appendChild(scrim);
  (scrim.querySelector('input, button') || scrim).focus?.();
  return { close, el: scrim };
}

export function lightbox(src, title, caption) {
  const { close, el } = sheet(`<img src="${esc(src)}" alt="${esc(caption || title)}"><div class="cap"><b>${esc(title)}</b>${esc(caption)}</div>`, { cls: 'lightbox' });
  el.querySelector('img').addEventListener('click', close);
}

/** Fade sections in as they scroll into view. */
export function reveal(root = document) {
  const els = $$('.reveal, [data-reveal]', root);
  if (!('IntersectionObserver' in window)) { els.forEach(e => e.classList.add('in')); return; }
  const io = new IntersectionObserver(entries => entries.forEach(en => {
    if (en.isIntersecting) { en.target.classList.add('in'); io.unobserve(en.target); }
  }), { rootMargin: '0px 0px -12% 0px' });
  els.forEach(e => io.observe(e));
}

/** "developer+90d" or "developer@+90d" -> {persona: "developer", clock: "+90d"} */
export function parseRun(name) {
  const m = /^([a-z_-]+?)\s*(?:[@/|:·]\s*)?([+-]?\d+d?)?$/i.exec(name || '');
  return m ? { persona: m[1], clock: m[2] || '0' } : { persona: name, clock: '0' };
}
