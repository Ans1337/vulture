/** Count a figure up from zero, once. Elements carry data-count="97". */
export function countUp(root) {
  const still = matchMedia('(prefers-reduced-motion: reduce)').matches;
  root.querySelectorAll('[data-count]').forEach(el => {
    const to = +el.dataset.count;
    if (still || !to) { el.textContent = to; return; }
    const t0 = performance.now(), ms = 700;
    const step = now => {
      const k = Math.min(1, (now - t0) / ms), e = 1 - Math.pow(1 - k, 3);
      el.textContent = Math.round(to * e);
      if (k < 1) requestAnimationFrame(step);
    };
    requestAnimationFrame(step);
  });
}

/** Swap page content, cross-fading where the browser supports view transitions. */
export function swap(fn) {
  if (!document.startViewTransition || document.hidden || matchMedia('(prefers-reduced-motion: reduce)').matches) return fn();
  const t = document.startViewTransition(fn);
  // a skipped transition (hidden tab, a newer navigation) still runs fn, so the rejection carries no news
  for (const p of [t.ready, t.finished, t.updateCallbackDone]) p?.catch(() => {});
}

